#!/usr/bin/env python3
"""Scramble a Zondision evaluation key for wiz3D's ZimoAdapter.

Zondision's terms (lib/Zondision/Stereopticon wiz3D StereoLoom terms.txt):
    "The key is never in a text file or the public repository."

The runtime key (Stereo Loom / wiz3D's own) stays in a gitignored header
(ZimoKey.private.h). The *evaluation* key is Zondision's own, published in
their SDK sample, and technically "free to release" -- but we still keep it
obfuscated in-source as a matter of policy, so no plaintext key of any kind
lives in the public repo.

This script XOR-scrambles a plaintext key with the same byte pattern that
ZimoAdapter.cpp's Scrambled template applies at compile time. The output is
a short .inc file with a `unsigned char[]` initializer that the cpp includes
and descrambles on demand.

To rotate when the eval key expires (Zondision's 2027-01-01 cutoff, or any
future rotation):
    1. Fetch the new plaintext eval key from Zondision's SDK sample
       (lib/Zondision/3DS_CSDK_V*/docs or their developer portal).
    2. Run: python tools/scramble_eval_key.py "<new plaintext key>"
    3. Commit the regenerated ZimoAdapter/ZimoEvalKey.scrambled.inc.

The plaintext key passes through argv, which may land in your shell history.
If that matters to you, clear it after running (`history -c` / Clear-History)
or echo the key from a gitignored file instead of pasting it.
"""

import sys
from pathlib import Path


def key_byte(i: int) -> int:
    """Mirror ZimoAdapter.cpp's KeyByte(i). Must stay byte-for-byte identical."""
    return (0xA7 ^ ((i * 0x3D) & 0xFF) ^ (((i >> 3) * 0x5B) & 0xFF)) & 0xFF


def scramble(plaintext: str) -> list[int]:
    # Match SR-Loom's Scrambled<sizeof(STR)>: include the terminating NUL.
    buf = (plaintext + "\0").encode("ascii")
    return [b ^ key_byte(i) for i, b in enumerate(buf)]


def format_rows(scrambled: list[int]) -> str:
    rows = []
    for i in range(0, len(scrambled), 8):
        rows.append("    " + ", ".join(f"0x{b:02X}" for b in scrambled[i : i + 8]) + ",")
    return "\n".join(rows)


def main() -> int:
    if len(sys.argv) != 2 or not sys.argv[1]:
        print('Usage: scramble_eval_key.py "<plaintext-key>"', file=sys.stderr)
        return 1
    plaintext = sys.argv[1]
    scrambled = scramble(plaintext)
    inc_path = Path(__file__).resolve().parent.parent / "ZimoAdapter" / "ZimoEvalKey.scrambled.inc"
    inc_path.parent.mkdir(parents=True, exist_ok=True)
    body = (
        "// ZimoEvalKey.scrambled.inc -- regenerated by tools/scramble_eval_key.py.\n"
        "// Pre-scrambled Zondision evaluation key. XOR with the KeyByte pattern in\n"
        "// ZimoAdapter.cpp to recover. Evaluation keys expire (Zondision's cutoff is\n"
        "// 2027-01-01 for the current one); re-run the tool with a fresh plaintext.\n"
        "#pragma once\n"
        "\n"
        "static constexpr unsigned char kEvalKeyScrambled[] = {\n"
        + format_rows(scrambled)
        + "\n};\n"
        "static constexpr unsigned kEvalKeyScrambledLen = sizeof(kEvalKeyScrambled);   // includes terminating NUL\n"
    )
    inc_path.write_text(body, encoding="ascii")
    print(f"wrote {inc_path} ({len(scrambled)} bytes including NUL)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
